-- PostgreSQL baseline: the schema SQLite reaches after migrations 1-30
-- (server/migrations/001-030 plus the repairs in server/src/db.ts).
-- Generated from that schema, then reviewed. Type mapping:
--   TEXT    -> TEXT COLLATE "C"  (byte order, as SQLite's BINARY collation)
--   INTEGER -> BIGINT            (epoch-millisecond values exceed int4)
--   INTEGER -> DOUBLE PRECISION  for columns SQLite fills with fractional
--                                seconds: contributions.duration_seconds,
--                                cycles.seconds_used,
--                                contribution_quota_windows.seconds_used
--   REAL    -> DOUBLE PRECISION
--   AUTOINCREMENT -> GENERATED BY DEFAULT AS IDENTITY
-- Every foreign key is DEFERRABLE (initially immediate) so the one-off
-- SQLite import can load tables in any order inside one transaction.
-- A later schema change needs a SQLite migration and a matching file here
-- (server/migrations/postgres/NNN-*.sql); tests/postgres parity checks it.

CREATE TABLE schema_migrations (
  version BIGINT PRIMARY KEY,
  applied_at TEXT COLLATE "C" NOT NULL
);

