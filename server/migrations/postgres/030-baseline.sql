-- SQLite's julianday() for ISO-8601 text, used by operational metrics.
CREATE FUNCTION julianday(value TEXT) RETURNS DOUBLE PRECISION
LANGUAGE sql STABLE AS $$
  SELECT EXTRACT(EPOCH FROM value::timestamptz) / 86400.0 + 2440587.5
$$;

-- Real profiles mirror into the media actor table (SQLite migration 022).
CREATE FUNCTION real_profile_media_actor_insert() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO profiles (id, display_name, avatar_label, is_synthetic)
  VALUES (NEW.id, NEW.display_name, 'REAL ACCOUNT', 0)
  ON CONFLICT DO NOTHING;
  RETURN NULL;
END;
$$;

CREATE TRIGGER real_profile_media_actor_insert
AFTER INSERT ON real_profiles
FOR EACH ROW EXECUTE FUNCTION real_profile_media_actor_insert();

CREATE FUNCTION real_profile_media_actor_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE profiles SET display_name = NEW.display_name
  WHERE id = NEW.id AND is_synthetic = 0;
  RETURN NULL;
END;
$$;

CREATE TRIGGER real_profile_media_actor_update
AFTER UPDATE OF display_name ON real_profiles
FOR EACH ROW EXECUTE FUNCTION real_profile_media_actor_update();

CREATE FUNCTION real_profile_media_actor_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM profiles WHERE id = OLD.id AND is_synthetic = 0;
  RETURN NULL;
END;
$$;

CREATE TRIGGER real_profile_media_actor_delete
AFTER DELETE ON real_profiles
FOR EACH ROW EXECUTE FUNCTION real_profile_media_actor_delete();

